#!/usr/bin/env node
// FALLBACK ONLY (Round 9 plan, decisions 10 and 27). Not wired into any
// script today: both apps import ../../design-tokens/index.css directly.
//
// Use it only if a deploy cannot see files outside the app folder (Vercel
// Root Directory set to the app with "Include files outside the root
// directory" off). Then:
//   1. node design-tokens/sync.mjs            copies every *.css here into
//      <app>/app/design-tokens/ for website-v3 and platform
//   2. change the app's import to  @import "./design-tokens/index.css";
//   3. COMMIT the copies (never gitignore them; the deploy needs them)
//   4. run with --check in lint/CI (exits 1 when a copy drifts)
//
//   node design-tokens/sync.mjs [--app website-v3|platform] [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(src, '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const appArg = args.includes('--app') ? args[args.indexOf('--app') + 1] : null;
const apps = appArg ? [appArg] : ['website-v3', 'platform'];
const files = fs.readdirSync(src).filter((f) => f.endsWith('.css')).sort();
const banner = '/* GENERATED by design-tokens/sync.mjs from /design-tokens. Do not edit; edit the source and re-run. */\n';

let drift = 0;
for (const app of apps) {
  const dest = path.join(repo, app, 'app', 'design-tokens');
  if (!check) fs.mkdirSync(dest, { recursive: true });
  for (const f of files) {
    const want = banner + fs.readFileSync(path.join(src, f), 'utf8');
    const target = path.join(dest, f);
    const have = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (have === want) continue;
    if (check) {
      console.log(`drift: ${path.relative(repo, target)}`);
      drift++;
    } else {
      fs.writeFileSync(target, want);
      console.log(`wrote ${path.relative(repo, target)}`);
    }
  }
}
if (check) {
  console.log(drift ? `${drift} file(s) out of sync` : 'design-tokens copies in sync');
  process.exit(drift ? 1 : 0);
}
